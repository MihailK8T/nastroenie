-- ---------------------------------------------------------------------------
-- Профиль создаётся автоматически при регистрации.
-- Ник берётся из raw_user_meta_data.nick, иначе из email.
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nick, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nick', split_part(new.email, '@', 1)),
    new.email
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
  before update on public.profiles
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Покупка тарифа. Демо-оплата: списание не проводится.
-- В продакшене вызывать только после подтверждения платежа на сервере.
-- ---------------------------------------------------------------------------
create or replace function public.purchase_plan(p_code text)
returns timestamptz
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plan public.plans%rowtype;
  v_until timestamptz;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;

  select * into v_plan from public.plans where code = p_code;
  if not found then
    raise exception 'unknown plan';
  end if;

  if v_plan.days = 0 then
    update public.profiles
       set plan = 'normal', plan_until = null, updated_at = now()
     where id = auth.uid();
    return null;
  end if;

  select case
           when plan = p_code and plan_until > now() then plan_until
           else now()
         end
    into v_until
    from public.profiles
   where id = auth.uid();

  v_until := coalesce(v_until, now()) + make_interval(days => v_plan.days);

  update public.profiles
     set plan = p_code, plan_until = v_until, updated_at = now()
   where id = auth.uid();

  if not found then
    raise exception 'profile not found';
  end if;

  return v_until;
end;
$$;

revoke all on function public.purchase_plan(text) from public;
grant execute on function public.purchase_plan(text) to authenticated;

-- ---------------------------------------------------------------------------
-- Покупка монет. Демо-оплата; в продакшене цена должна приходить от платёжки.
-- ---------------------------------------------------------------------------
create or replace function public.buy_coins(p_coins integer)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_price integer;
  v_balance integer;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;

  v_price := case p_coins
    when 500 then 99
    when 1500 then 249
    when 4000 then 599
    else null
  end;

  if v_price is null then
    raise exception 'unknown coin pack';
  end if;

  update public.profiles
     set coins = coins + p_coins, updated_at = now()
   where id = auth.uid()
   returning coins into v_balance;

  if not found then
    raise exception 'profile not found';
  end if;

  insert into public.coin_purchases (user_id, coins, price)
  values (auth.uid(), p_coins, v_price);

  return v_balance;
end;
$$;

revoke all on function public.buy_coins(integer) from public;
grant execute on function public.buy_coins(integer) to authenticated;

-- ---------------------------------------------------------------------------
-- Вход по нику и паролю для сайта и игры.
-- Таблица закрыта: клиент работает только через RPC ниже.
-- ---------------------------------------------------------------------------
create table if not exists public.mc_accounts (
  id uuid primary key default gen_random_uuid(),
  nick text not null,
  nick_lower text not null unique,
  email text,
  password_hash text not null,
  created_at timestamptz not null default now()
);

alter table public.mc_accounts enable row level security;
revoke all on public.mc_accounts from anon, authenticated;

create or replace function public.mc_register(p_name text, p_password text, p_email text default '')
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nick text := btrim(coalesce(p_name, ''));
  v_email text := nullif(btrim(coalesce(p_email, '')), '');
begin
  if v_nick !~ '^[A-Za-z0-9_]{3,16}$' then
    return 'bad';
  end if;
  if length(coalesce(p_password, '')) < 6 or length(p_password) > 128 then
    return 'bad';
  end if;
  if exists (select 1 from public.mc_accounts where nick_lower = lower(v_nick)) then
    return 'exists';
  end if;

  insert into public.mc_accounts (nick, nick_lower, email, password_hash)
  values (v_nick, lower(v_nick), v_email, crypt(p_password, gen_salt('bf', 12)));

  return 'ok';
exception
  when unique_violation then
    return 'exists';
end;
$$;

revoke all on function public.mc_register(text, text, text) from public;
grant execute on function public.mc_register(text, text, text) to anon, authenticated;

create or replace function public.mc_verify(p_name text, p_password text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hash text;
begin
  select password_hash into v_hash
    from public.mc_accounts
   where nick_lower = lower(btrim(coalesce(p_name, '')));

  if v_hash is null then
    perform crypt(coalesce(p_password, ''), gen_salt('bf', 12));
    return false;
  end if;

  return crypt(coalesce(p_password, ''), v_hash) = v_hash;
end;
$$;

revoke all on function public.mc_verify(text, text) from public;
grant execute on function public.mc_verify(text, text) to anon, authenticated;

create or replace function public.mc_email(p_name text)
returns text
language sql
security definer
set search_path = public
as $$
  select coalesce(email, '')
    from public.mc_accounts
   where nick_lower = lower(btrim(coalesce(p_name, '')))
   limit 1;
$$;

revoke all on function public.mc_email(text) from public;
grant execute on function public.mc_email(text) to anon, authenticated;
