-- ---------------------------------------------------------------------------
-- Профили: ник, тариф, срок и монеты. Прямых записей от клиента нет.
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nick text not null check (nick ~ '^[A-Za-z0-9_]{3,16}$'),
  email text,
  plan text not null default 'normal' references public.plans(code),
  plan_until timestamptz,
  coins integer not null default 0 check (coins >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_nick_lower_key
  on public.profiles (lower(nick));

alter table public.profiles enable row level security;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles
  for select to authenticated
  using (auth.uid() = id);

revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;

