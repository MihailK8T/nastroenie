create table if not exists public.mc_accounts (
  nick_lower text primary key,
  nick text not null,
  password_hash text not null,
  email text,
  banned boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.mc_accounts enable row level security;
revoke all on public.mc_accounts from anon, authenticated;

do $$
begin
  if exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'mc_accounts' and column_name = 'pass_hash'
  ) and not exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'mc_accounts' and column_name = 'password_hash'
  ) then
    alter table public.mc_accounts rename column pass_hash to password_hash;
  end if;
end $$;

-- --------------------------------------------------------------------------
-- Регистрация и вход
-- --------------------------------------------------------------------------
create or replace function public.mc_register(p_name text, p_password text, p_email text default null)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_nick text := btrim(coalesce(p_name, ''));
  v_key text := lower(btrim(coalesce(p_name, '')));
  v_pass text := coalesce(p_password, '');
begin
  if v_nick !~ '^[A-Za-z0-9_]{3,16}$' then
    raise exception 'bad nick';
  end if;

  if length(v_pass) < 6 or length(v_pass) > 64 then
    raise exception 'bad password';
  end if;

  if exists (select 1 from public.mc_accounts where nick_lower = v_key) then
    return 'exists';
  end if;

  insert into public.mc_accounts (nick_lower, nick, password_hash, email)
  values (v_key, v_nick, crypt(v_pass, gen_salt('bf', 10)), nullif(btrim(coalesce(p_email, '')), ''));

  return 'ok';
exception
  when unique_violation then return 'exists';
end;
$$;

create or replace function public.mc_verify(p_name text, p_password text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_ok boolean;
begin
  select (password_hash = crypt(coalesce(p_password, ''), password_hash)) and not banned
    into v_ok
    from public.mc_accounts
   where nick_lower = lower(btrim(coalesce(p_name, '')));

  return coalesce(v_ok, false);
end;
$$;

create or replace function public.mc_email(p_name text)
returns text
language sql
security definer
set search_path = public, extensions
as $$
  select email from public.mc_accounts where nick_lower = lower(btrim(coalesce(p_name, '')));
$$;

-- --------------------------------------------------------------------------
-- Сотрудники поддержки
-- --------------------------------------------------------------------------
create table if not exists public.staff (
  id bigint generated by default as identity primary key,
  login text not null,
  name text not null,
  pass_hash text not null,
  role text not null check (role in ('owner', 'admin', 'moderator')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by text
);

create unique index if not exists staff_login_key on public.staff (lower(login));

alter table public.staff enable row level security;
revoke all on public.staff from anon, authenticated;

create table if not exists public.staff_sessions (
  token text primary key,
  staff_id bigint not null references public.staff(id) on delete cascade,
  expires_at timestamptz not null
);

alter table public.staff_sessions enable row level security;
revoke all on public.staff_sessions from anon, authenticated;

create table if not exists public.player_sessions (
  token text primary key,
  nick_lower text not null references public.mc_accounts(nick_lower) on delete cascade,
  expires_at timestamptz not null
);

alter table public.player_sessions enable row level security;
revoke all on public.player_sessions from anon, authenticated;

-- --------------------------------------------------------------------------
-- Заявки и сообщения
-- --------------------------------------------------------------------------
create table if not exists public.support_threads (
  id bigint generated by default as identity primary key,
  nick_lower text not null unique references public.mc_accounts(nick_lower) on delete cascade,
  status text not null default 'open' check (status in ('open', 'claimed', 'closed')),
  claimed_by bigint references public.staff(id) on delete set null,
  staff_last_seen_id bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  closed_at timestamptz
);

create index if not exists support_threads_status_idx on public.support_threads (status, updated_at desc);

alter table public.support_threads enable row level security;
revoke all on public.support_threads from anon, authenticated;

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.support_threads(id) on delete cascade,
  kind text not null check (kind in ('player', 'staff', 'system')),
  author_name text,
  body text not null,
  created_at timestamptz not null default now()
);

create index if not exists support_messages_thread_idx on public.support_messages (thread_id, id);

alter table public.support_messages enable row level security;
revoke all on public.support_messages from anon, authenticated;

