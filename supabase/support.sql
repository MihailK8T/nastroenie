           'created_at', s.created_at,
           'created_by', s.created_by,
           'claimed', (select count(*) from public.support_threads t where t.claimed_by = s.id),
           'closed', (select count(*) from public.support_threads t where t.claimed_by = s.id and t.status = 'closed')
         ) order by s.id), '[]'::json)
    into v_rows
    from public.staff s;

  return v_rows;
end;
$$;

create or replace function public.staff_create(
  p_token text,
  p_login text,
  p_name text,
  p_password text,
  p_role text
)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'admin');
  v_login text := lower(btrim(coalesce(p_login, '')));
  v_name text := btrim(coalesce(p_name, ''));
  v_role text := lower(btrim(coalesce(p_role, 'moderator')));
  v_password text := coalesce(p_password, '');
  v_new public.staff;
begin
  if v_role not in ('moderator', 'admin') then
    raise exception 'bad role';
  end if;

  if v_role = 'admin' and v_staff.role <> 'owner' then
    raise exception 'forbidden';
  end if;

  if v_login !~ '^[a-z0-9_.-]{3,24}$' then
    raise exception 'bad login';
  end if;

  if length(v_name) < 2 or length(v_name) > 40 then
    raise exception 'bad name';
  end if;

  if length(v_password) < 8 or length(v_password) > 64 then
    raise exception 'bad password';
  end if;

  if exists (select 1 from public.staff where lower(login) = v_login) then
    raise exception 'login taken';
  end if;

  insert into public.staff (login, name, pass_hash, role, created_by)
  values (v_login, v_name, crypt(v_password, gen_salt('bf', 10)), v_role, v_staff.name)
  returning * into v_new;

  return json_build_object(
    'id', v_new.id,
    'login', v_new.login,
    'name', v_new.name,
    'role', v_new.role,
    'active', v_new.active
  );
end;
$$;

create or replace function public.staff_set_active(p_token text, p_staff_id bigint, p_active boolean)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'admin');
  v_target public.staff;
begin
  select * into v_target from public.staff where id = p_staff_id;

  if not found then
    raise exception 'not found';
  end if;

  if v_target.id = v_staff.id then
    raise exception 'self';
  end if;

  if v_target.role = 'owner' and v_staff.role <> 'owner' then
    raise exception 'forbidden';
  end if;

  update public.staff set active = p_active where id = v_target.id;

  return json_build_object('ok', true);
end;
$$;

