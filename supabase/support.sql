  if v_staff.pass_hash <> crypt(coalesce(p_password, ''), v_staff.pass_hash) then
    raise exception 'bad credentials';
  end if;

  delete from public.staff_sessions where expires_at < now();

  v_token := public.new_token();
  insert into public.staff_sessions (token, staff_id, expires_at)
  values (v_token, v_staff.id, now() + interval '12 hours');

  return json_build_object(
    'token', v_token,
    'login', v_staff.login,
    'name', v_staff.name,
    'role', v_staff.role
  );
end;
$$;

