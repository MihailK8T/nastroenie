create or replace function public.new_token()
returns text
language plpgsql
volatile
set search_path = public, extensions
as $$
begin
  return encode(gen_random_bytes(24), 'hex');
end;
$$;

create or replace function public.staff_require(p_token text, p_min_role text default 'moderator')
returns public.staff
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff;
  v_rank int;
  v_min int;
begin
  select st.* into v_staff
    from public.staff_sessions ss
    join public.staff st on st.id = ss.staff_id
   where ss.token = p_token
     and ss.expires_at > now()
     and st.active;

  if not found then
    raise exception 'unauthorized';
  end if;

  v_rank := case v_staff.role when 'owner' then 3 when 'admin' then 2 else 1 end;
  v_min := case coalesce(p_min_role, 'moderator') when 'owner' then 3 when 'admin' then 2 else 1 end;

  if v_rank < v_min then
    raise exception 'forbidden';
  end if;

  return v_staff;
end;
$$;

create or replace function public.support_player(p_token text)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_nick text;
begin
  select ps.nick_lower into v_nick
    from public.player_sessions ps
   where ps.token = p_token
     and ps.expires_at > now();

  if v_nick is null then
    raise exception 'unauthorized';
  end if;

  return v_nick;
end;
$$;

