create or replace function public.staff_stats(p_token text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_team json;
begin
  select coalesce(json_agg(json_build_object(
           'id', s.id,
           'name', s.name,
           'role', s.role,
           'active', s.active,
           'claimed', (select count(*) from public.support_threads t where t.claimed_by = s.id),
           'closed', (select count(*) from public.support_threads t where t.claimed_by = s.id and t.status = 'closed'),
           'replies', (select count(*) from public.support_messages m where m.kind = 'staff' and m.author_name = s.name)
         ) order by s.id), '[]'::json)
    into v_team
    from public.staff s;

  return json_build_object(
    'threads_total', (select count(*) from public.support_threads),
    'threads_open', (select count(*) from public.support_threads where status = 'open'),
    'threads_claimed', (select count(*) from public.support_threads where status = 'claimed'),
    'threads_closed', (select count(*) from public.support_threads where status = 'closed'),
    'messages', (select count(*) from public.support_messages where kind <> 'system'),
    'staff_total', (select count(*) from public.staff),
    'staff_active', (select count(*) from public.staff where active),
    'today', (select count(*) from public.support_threads where created_at >= date_trunc('day', now())),
    'team', v_team
  );
end;
$$;

