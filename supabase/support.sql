create or replace function public.support_login(p_name text, p_password text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_key text := lower(btrim(coalesce(p_name, '')));
  v_acc public.mc_accounts;
  v_token text;
  v_thread public.support_threads;
begin
  select * into v_acc from public.mc_accounts where nick_lower = v_key;

  if not found then
    raise exception 'bad credentials';
  end if;

  if v_acc.banned then
    raise exception 'banned';
  end if;

  if v_acc.password_hash <> crypt(coalesce(p_password, ''), v_acc.password_hash) then
    raise exception 'bad credentials';
  end if;

  delete from public.player_sessions where expires_at < now();

  v_token := public.new_token();
  insert into public.player_sessions (token, nick_lower, expires_at)
  values (v_token, v_key, now() + interval '30 days');

  select * into v_thread from public.support_threads where nick_lower = v_key;

  if not found then
    insert into public.support_threads (nick_lower, status)
    values (v_key, 'open')
    returning * into v_thread;

    insert into public.support_messages (thread_id, kind, body)
    values (v_thread.id, 'system', 'Заявка создана');
  end if;

  return json_build_object(
    'token', v_token,
    'nick', v_acc.nick,
    'thread', v_thread.id,
    'status', v_thread.status
  );
end;
$$;

create or replace function public.support_state(p_token text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_key text := public.support_player(p_token);
  v_thread public.support_threads;
  v_acc public.mc_accounts;
  v_staff_name text;
  v_messages json;
begin
  select * into v_acc from public.mc_accounts where nick_lower = v_key;
  select * into v_thread from public.support_threads where nick_lower = v_key;

  if not found then
    raise exception 'no thread';
  end if;

  select name into v_staff_name from public.staff where id = v_thread.claimed_by;

  select coalesce(json_agg(q.m order by q.id), '[]'::json) into v_messages
    from (
      select s.id,
             json_build_object(
               'id', s.id,
               'kind', s.kind,
               'author', s.author_name,
               'body', s.body,
               'at', s.created_at
             ) as m
        from public.support_messages s
       where s.thread_id = v_thread.id
       order by s.id desc
       limit 300
    ) q;

  return json_build_object(
    'nick', v_acc.nick,
    'status', v_thread.status,
    'claimed', v_staff_name,
    'messages', v_messages
  );
end;
$$;

create or replace function public.support_send(p_token text, p_body text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_key text := public.support_player(p_token);
  v_body text := btrim(coalesce(p_body, ''));
  v_thread public.support_threads;
  v_acc public.mc_accounts;
  v_reopened boolean := false;
begin
  if length(v_body) < 1 then
    raise exception 'empty message';
  end if;

  if length(v_body) > 2000 then
    v_body := left(v_body, 2000);
  end if;

  select * into v_acc from public.mc_accounts where nick_lower = v_key;

  select * into v_thread from public.support_threads where nick_lower = v_key for update;

  if not found then
    raise exception 'no thread';
  end if;

  if v_thread.status = 'closed' then
    update public.support_threads
       set status = 'open', closed_at = null, claimed_by = null, updated_at = now()
     where id = v_thread.id;
    v_reopened := true;
  else
    update public.support_threads set updated_at = now() where id = v_thread.id;
  end if;

  if v_reopened then
    insert into public.support_messages (thread_id, kind, body)
    values (v_thread.id, 'system', 'Заявка открыта заново');
  end if;

  insert into public.support_messages (thread_id, kind, author_name, body)
  values (v_thread.id, 'player', v_acc.nick, v_body);

  return json_build_object('ok', true, 'reopened', v_reopened);
end;
$$;

create or replace function public.support_close(p_token text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_key text := public.support_player(p_token);
  v_thread public.support_threads;
begin
  select * into v_thread from public.support_threads where nick_lower = v_key for update;

  if not found then
    raise exception 'no thread';
  end if;

  if v_thread.status = 'closed' then
    return json_build_object('ok', true);
  end if;

  update public.support_threads
     set status = 'closed', closed_at = now(), updated_at = now()
   where id = v_thread.id;

  insert into public.support_messages (thread_id, kind, body)
  values (v_thread.id, 'system', 'Игрок закрыл заявку');

  return json_build_object('ok', true);
end;
$$;

