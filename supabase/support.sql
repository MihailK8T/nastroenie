create or replace function public.staff_threads(p_token text, p_status text default null)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_status text := nullif(btrim(coalesce(p_status, '')), '');
  v_rows json;
begin
  select coalesce(json_agg(q.row order by q.updated_at desc), '[]'::json) into v_rows
    from (
      select th.updated_at,
             json_build_object(
               'id', th.id,
               'nick', a.nick,
               'status', th.status,
               'claimed', st.name,
               'created_at', th.created_at,
               'updated_at', th.updated_at,
               'last', lm.body,
               'last_at', lm.created_at,
               'unread', (
                 select count(*)
                   from public.support_messages m
                  where m.thread_id = th.id
                    and m.kind = 'player'
                    and m.id > th.staff_last_seen_id
               )
             ) as row
        from public.support_threads th
        join public.mc_accounts a on a.nick_lower = th.nick_lower
        left join public.staff st on st.id = th.claimed_by
        left join lateral (
          select m.body, m.created_at
            from public.support_messages m
           where m.thread_id = th.id
           order by m.id desc
           limit 1
        ) lm on true
       where v_status is null or th.status = v_status
    ) q;

  return v_rows;
end;
$$;

create or replace function public.staff_thread(p_token text, p_thread bigint)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_thread public.support_threads;
  v_acc public.mc_accounts;
  v_claimed text;
  v_messages json;
  v_last bigint;
begin
  select * into v_thread from public.support_threads where id = p_thread;

  if not found then
    raise exception 'not found';
  end if;

  select * into v_acc from public.mc_accounts where nick_lower = v_thread.nick_lower;
  select name into v_claimed from public.staff where id = v_thread.claimed_by;

  select coalesce(max(m.id), 0) into v_last from public.support_messages m where m.thread_id = v_thread.id;

  update public.support_threads
     set staff_last_seen_id = v_last
   where id = v_thread.id;

  select coalesce(json_agg(q.m order by q.id), '[]'::json) into v_messages
    from (
      select s.id,
             json_build_object(
               'id', s.id,
               'kind', s.kind,
               'author', s.author_name,
               'body', s.body,
               'at', s.created_at
             ) as m
        from public.support_messages s
       where s.thread_id = v_thread.id
       order by s.id desc
       limit 300
    ) q;

  return json_build_object(
    'id', v_thread.id,
    'nick', v_acc.nick,
    'status', v_thread.status,
    'claimed', v_claimed,
    'created_at', v_thread.created_at,
    'closed_at', v_thread.closed_at,
    'messages', v_messages
  );
end;
$$;

create or replace function public.staff_claim(p_token text, p_thread bigint)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_thread public.support_threads;
begin
  select * into v_thread from public.support_threads where id = p_thread for update;

  if not found then
    raise exception 'not found';
  end if;

  if v_thread.status = 'closed' then
    raise exception 'closed';
  end if;

  if v_thread.claimed_by is not null and v_thread.claimed_by <> v_staff.id then
    raise exception 'already claimed';
  end if;

  update public.support_threads
     set status = 'claimed', claimed_by = v_staff.id, updated_at = now()
   where id = v_thread.id;

  insert into public.support_messages (thread_id, kind, author_name, body)
  values (v_thread.id, 'system', v_staff.name || ' подключился к чату');

  return json_build_object('ok', true);
end;
$$;

create or replace function public.staff_reply(p_token text, p_thread bigint, p_body text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_thread public.support_threads;
  v_body text := btrim(coalesce(p_body, ''));
begin
  if length(v_body) < 1 then
    raise exception 'empty message';
  end if;

  if length(v_body) > 2000 then
    v_body := left(v_body, 2000);
  end if;

  select * into v_thread from public.support_threads where id = p_thread for update;

  if not found then
    raise exception 'not found';
  end if;

  if v_thread.status = 'closed' then
    raise exception 'closed';
  end if;

  if v_thread.claimed_by is null then
    update public.support_threads
       set status = 'claimed', claimed_by = v_staff.id
     where id = v_thread.id;

    insert into public.support_messages (thread_id, kind, author_name, body)
    values (v_thread.id, 'system', v_staff.name || ' подключился к чату');
  elsif v_thread.claimed_by <> v_staff.id then
    raise exception 'claimed by another';
  end if;

  insert into public.support_messages (thread_id, kind, author_name, body)
  values (v_thread.id, 'staff', v_staff.name, v_body);

  update public.support_threads
     set updated_at = now(),
         staff_last_seen_id = (select coalesce(max(m.id), 0) from public.support_messages m where m.thread_id = v_thread.id)
   where id = v_thread.id;

  return json_build_object('ok', true);
end;
$$;

create or replace function public.staff_close(p_token text, p_thread bigint)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_staff public.staff := public.staff_require(p_token, 'moderator');
  v_thread public.support_threads;
begin
  select * into v_thread from public.support_threads where id = p_thread for update;

  if not found then
    raise exception 'not found';
  end if;

  if v_thread.status = 'closed' then
    return json_build_object('ok', true);
  end if;

  if v_thread.claimed_by is not null and v_thread.claimed_by <> v_staff.id and v_staff.role = 'moderator' then
    raise exception 'claimed by another';
  end if;

  update public.support_threads
     set status = 'closed',
         claimed_by = coalesce(v_thread.claimed_by, v_staff.id),
         closed_at = now(),
         updated_at = now()
   where id = v_thread.id;

  insert into public.support_messages (thread_id, kind, author_name, body)
  values (v_thread.id, 'system', v_staff.name || ' закрыл заявку');

  return json_build_object('ok', true);
end;
$$;

