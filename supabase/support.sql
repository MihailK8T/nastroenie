create or replace function public.staff_bootstrap(p_login text, p_name text, p_password text)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_login text := lower(btrim(coalesce(p_login, '')));
  v_name text := btrim(coalesce(p_name, ''));
  v_password text := coalesce(p_password, '');
  v_staff public.staff;
  v_token text;
begin
  if exists (select 1 from public.staff) then
    raise exception 'already configured';
  end if;

  if v_login !~ '^[a-z0-9_.-]{3,24}$' then
    raise exception 'bad login';
  end if;

  if length(v_name) < 2 or length(v_name) > 40 then
    raise exception 'bad name';
  end if;

  if length(v_password) < 8 or length(v_password) > 64 then
    raise exception 'bad password';
  end if;

  insert into public.staff (login, name, pass_hash, role, created_by)
  values (v_login, v_name, crypt(v_password, gen_salt('bf', 10)), 'owner', 'bootstrap')
  returning * into v_staff;

  delete from public.staff_sessions where expires_at < now();

  v_token := public.new_token();
  insert into public.staff_sessions (token, staff_id, expires_at)
  values (v_token, v_staff.id, now() + interval '12 hours');

  return json_build_object(
    'token', v_token,
    'login', v_staff.login,
    'name', v_staff.name,
    'role', v_staff.role
  );
end;
$$;

create or replace function public.staff_login(p_login text, p_password text)
